"""Publish the analysed sample files to the web app, so judges can open them without spending quota.

Reads each sample's manifest (``data/samples/<slug>``) and the analysis that ``run_sample`` saved
(``eval/out/samples/sample-<slug>.json``), then writes:

- ``web/src/samples.ts``: a short summary of every file, for the landing page;
- ``web/public/samples/<slug>/file.json``: the full credit file, with every reading;
- ``web/public/samples/<slug>/*.webp``: the evidence photos, resized for the web.

    python eval/export_samples.py
"""

from __future__ import annotations

import argparse
import json
from datetime import datetime
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SLUGS = ("bu-sari", "pak-joko", "pak-hendra")
FILE_NUMBERS = {"bu-sari": "LL-2610-0142", "pak-joko": "LL-2610-0143", "pak-hendra": "LL-2610-0144"}


def _camel_key(key: str) -> str:
    head, *rest = key.split("_")
    return head + "".join(word.title() for word in rest)


def camel(value):
    """Give every key the camelCase the web app expects, whatever model produced it."""
    if isinstance(value, dict):
        return {_camel_key(k): camel(v) for k, v in value.items()}
    if isinstance(value, list):
        return [camel(v) for v in value]
    return value


def export(slug: str, data: Path) -> dict:
    manifest = json.loads((data / slug / "manifest.json").read_text())
    saved = ROOT / "eval/out/samples" / f"sample-{slug}.json"
    result = camel(json.loads(saved.read_text()))
    out = ROOT / "web/public/samples" / slug
    out.mkdir(parents=True, exist_ok=True)

    evidence = []
    for item in manifest["evidence"]:
        source = data / slug / item["path"]
        if item["type"] == "interview_audio":
            name = Path(item["path"]).name  # recordings are published as they are
            (out / name).write_bytes(source.read_bytes())
        else:
            name = Path(item["path"]).with_suffix(".webp").name
            image = Image.open(source).convert("RGB")
            image.thumbnail((900, 1400))
            image.save(out / name, quality=74, method=6)
        evidence_id = Path(item["path"]).stem
        evidence.append(
            {
                "id": evidence_id,
                "type": item["type"],
                "image": f"/samples/{slug}/{name}",
                "capturedAt": item["capturedAt"],
                "reading": result["extractions"].get(evidence_id),
            }
        )

    application = manifest["application"]
    file = {
        "slug": slug,
        "fileNumber": FILE_NUMBERS[slug],
        "application": application,
        "evidence": evidence,
        **{k: v for k, v in result.items() if k != "extractions"},
    }
    (out / "file.json").write_text(json.dumps(file, ensure_ascii=False, indent=1))

    policy, cashflow = result["policy"], result["cashflow"]
    return {
        "slug": slug,
        "fileNumber": FILE_NUMBERS[slug],
        "alias": application["alias"],
        "businessType": application["businessType"],
        "city": application["city"],
        "yearsOperating": application["yearsOperating"],
        "amount": application["amount"],
        "tenorMonths": application["tenorMonths"],
        "assessment": result["assessment"],
        "revenueLow": cashflow["revenueLow"],
        "revenueHigh": cashflow["revenueHigh"],
        "maxInstallment": policy["maxInstallment"],
        "requestedInstallment": policy["requestedInstallment"],
        "withinPolicy": policy["withinPolicy"],
        "evidenceStrength": policy["evidenceStrength"],
        "evidenceCount": len(evidence),
        "findings": [{"severity": f["severity"], "text": f["text"]} for f in result["findings"]],
        "headline": result["memo"]["headline"],
        "preparedAt": datetime.fromtimestamp(saved.stat().st_mtime).date().isoformat(),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description="Publish analysed sample files to the web app")
    parser.add_argument("--data", type=Path, default=ROOT / "data/samples")
    args = parser.parse_args()
    summaries = [export(slug, args.data) for slug in SLUGS]
    body = json.dumps(summaries, ensure_ascii=False, indent=2)
    (ROOT / "web/src/samples.ts").write_text(
        "// Generated by eval/export_samples.py from real analyses of the fictional sample files.\n"
        "// Every figure was computed by code from the evidence; do not edit by hand.\n"
        "import type { SampleSummary } from './types.ts'\n\n"
        f"export const SAMPLES: SampleSummary[] = {body}\n"
    )
    for s in summaries:
        print(f"{s['slug']}: {s['assessment']}, {s['evidenceCount']} items, "
              f"{len(s['findings'])} findings")


if __name__ == "__main__":
    main()
